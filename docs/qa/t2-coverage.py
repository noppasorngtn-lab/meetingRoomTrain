#!/usr/bin/env python3
"""T2 coverage matrix for the mrr project: which acceptance criteria (AC) have a test that cites them.

Run from anywhere:   python docs/qa/t2-coverage.py            (prints Markdown)
                     python docs/qa/t2-coverage.py --write    (writes docs/qa/t2-coverage-tables.md)
                     python docs/qa/t2-coverage.py --jest results.json   (adds a jest run summary,
                         made with: cd apps/api && npx jest --json --outputFile=results.json)

Inputs (read only):
  .aeon/design/modules/mrr/functions.json   AC -> EX and BR (the design's own mapping)
  docs/wiki/examples/EX-*.md                EX kind (happy / exception / boundary / alternate)
  apps/api/test/**/*.ts, apps/web/src/__tests__/*.tsx   tests that cite `AC-mrr-NNN`
  docs/qa/e2e-ex-map.json                   which EX the Playwright specs cover (kept by hand, see the file)
  docs/wiki/nfr/NFR-*.md, test/e2e, apps/*/test   NFR ids cited by tests

What "covered" means here: a test file cites the AC id. That is traceability, not proof the assertion is
right; read the tests of anything that matters (see t2-coverage-report.md for what was read).
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.stdout.reconfigure(encoding='utf-8')


def read(p: Path) -> str:
    return p.read_text(encoding='utf-8')


def cited(paths, pattern):
    """id -> set of file names, for every file in `paths` that contains the id."""
    out: dict[str, set[str]] = {}
    for p in paths:
        for m in set(re.findall(pattern, read(p))):
            out.setdefault(m, set()).add(p.name)
    return out


acceptance = json.loads(read(ROOT / '.aeon/design/modules/mrr/functions.json'))['acceptance']
ex_kind = {
    p.stem: re.search(r'^kind:\s*(\w+)', read(p), re.M).group(1)
    for p in (ROOT / 'docs/wiki/examples').glob('EX-*.md')
}
api = cited((ROOT / 'apps/api/test').rglob('*.ts'), r'AC-mrr-\d+')
web = cited((ROOT / 'apps/web/src/__tests__').glob('*.tsx'), r'AC-mrr-\d+')
e2e_map = json.loads(read(ROOT / 'docs/qa/e2e-ex-map.json'))['covers']
e2e = set(e2e_map)

rows = []
for a in acceptance:
    layers = tuple(n for n, ok in (('api', a['id'] in api), ('web', a['id'] in web), ('e2e', a.get('example') in e2e)) if ok)
    rows.append({'ac': a['id'], 'ex': a.get('example') or '—', 'kind': ex_kind.get(a.get('example'), 'no EX (design-only AC)'), 'rules': a['rules'], 'layers': layers})

out: list[str] = []
w = out.append

w('# T2 coverage tables (generated by docs/qa/t2-coverage.py — do not edit by hand)\n')
w(f'AC in design: **{len(rows)}** · EX in wiki: **{len(ex_kind)}**\n')

w('## AC by test layer\n')
w('| layers citing the AC | ACs |\n|---|---|')
by_layer = Counter(r['layers'] for r in rows)
for k, v in sorted(by_layer.items(), key=lambda x: -x[1]):
    w(f"| {' + '.join(k) or '**none**'} | {v} |")
uncited = [r['ac'] for r in rows if not r['layers']]
w(f"\nACs with no test citing them: {', '.join(uncited) or 'none'}")
no_api = [r for r in rows if 'api' not in r['layers']]
w(f"\nACs with no API-layer test citing them: {', '.join(r['ac'] + ' (' + '+'.join(r['layers']) + ')' for r in no_api) or 'none'}")
orphans = sorted(set(ex_kind) - {r['ex'] for r in rows})
w(f"\nEX with no AC (expected only for superseded rules, e.g. BR-mrr-010@v1): {', '.join(orphans) or 'none'}")

w('\n## Per rule\n')
w('| BR | AC covered | kinds covered | kinds in EX but not covered | uncovered AC |\n|---|---|---|---|---|')
per_br: dict[str, list] = {}
for r in rows:
    for b in r['rules']:
        per_br.setdefault(b, []).append(r)
for b in sorted(per_br):
    L = per_br[b]
    cov = [r for r in L if r['layers']]
    kc = {r['kind'] for r in cov}
    ka = {r['kind'] for r in L}
    w(f"| {b} | {len(cov)}/{len(L)} | {', '.join(sorted(kc))} | {', '.join(sorted(ka - kc)) or '—'} | {', '.join(r['ac'] for r in L if not r['layers']) or '—'} |")

w('\n## Playwright (E2E) coverage of EX — from docs/qa/e2e-ex-map.json\n')
w('| EX | kind | E2E cases | note |\n|---|---|---|---|')
for ex, v in sorted(e2e_map.items()):
    w(f"| {ex} | {ex_kind.get(ex, '?')} | {v['cases']} | {v.get('note', '')} |")

w('\n## NFR cited by a test\n')
tests = list((ROOT / 'apps/api/test').rglob('*.ts')) + list((ROOT / 'apps/web/src/__tests__').glob('*.tsx')) + list((ROOT / 'test/e2e').glob('*.ts'))
nfr_cites = cited(tests, r'NFR-mrr-\d+')
w('| NFR | requirement | cited by |\n|---|---|---|')
for p in sorted((ROOT / 'docs/wiki/nfr').glob('NFR-*.md')):
    desc = re.search(r'^description:\s*(.+)$', read(p), re.M).group(1)
    w(f"| {p.stem} | {desc} | {', '.join(sorted(nfr_cites.get(p.stem, []))) or '**none**'} |")

if '--jest' in sys.argv:
    j = json.loads(read(Path(sys.argv[sys.argv.index('--jest') + 1])))
    w('\n## API jest run\n')
    w(f"suites {j['numPassedTestSuites']}/{j['numTotalTestSuites']} passed · tests {j['numPassedTests']}/{j['numTotalTests']} passed · "
      f"failed {j['numFailedTests']} · pending {j['numPendingTests']}")
    for s in j['testResults']:
        if s['status'] != 'passed':
            w(f"- {s['name']}: {s['status']}")

text = '\n'.join(out) + '\n'
if '--write' in sys.argv:
    (ROOT / 'docs/qa/t2-coverage-tables.md').write_text(text, encoding='utf-8', newline='\n')
    print('wrote docs/qa/t2-coverage-tables.md')
else:
    print(text)
